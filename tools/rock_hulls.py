#!/usr/bin/env python3
"""Collision for the owner's Moon rocks, without touching his models: the convex hull of each rock
(and of each separate boulder in the rock field), cut down to its support points in 80 directions,
written as GDScript constants to scripts/rock_hulls.gd. Re-run it if a rock model is replaced."""
import json, struct, numpy as np

def load(f):
    d = open(f, 'rb').read(); l = struct.unpack('<I', d[12:16])[0]; j = json.loads(d[20:20 + l])
    bo = 20 + l; bl = struct.unpack('<I', d[bo:bo + 4])[0]; b = d[bo + 8:bo + 8 + bl]
    def acc(i):
        a = j['accessors'][i]; bv = j['bufferViews'][a['bufferView']]
        off = bv.get('byteOffset', 0) + a.get('byteOffset', 0)
        n = {'SCALAR': 1, 'VEC3': 3}[a['type']]
        dt = {5126: np.float32, 5125: np.uint32, 5123: np.uint16}[a['componentType']]
        x = np.frombuffer(b, dtype=dt, count=a['count'] * n, offset=off)
        return x.reshape(-1, n) if n > 1 else x
    vs, ts = [], []
    base = 0
    for m in j['meshes']:
        for p in m['primitives']:
            v = acc(p['attributes']['POSITION']).astype(np.float64); t = acc(p['indices']).reshape(-1, 3).astype(np.int64)
            vs.append(v); ts.append(t + base); base += len(v)
    return np.vstack(vs), np.vstack(ts)

def components(v, t):
    q = np.round(v / 1e-4).astype(np.int64)
    _, inv = np.unique(q, axis=0, return_inverse=True); inv = inv.ravel()
    par = np.arange(inv.max() + 1)
    def find(x):
        while par[x] != x:
            par[x] = par[par[x]]; x = par[x]
        return x
    for a, b, c in inv[t]:
        ra = find(a); par[find(b)] = ra; par[find(c)] = ra
    roots = np.array([find(i) for i in range(len(par))])
    vv = np.zeros((len(par), 3)); vv[inv] = v
    return [vv[roots == r] for r in np.unique(roots)]

def dirs(n=80):
    i = np.arange(n) + 0.5
    phi = np.arccos(1 - 2 * i / n); th = np.pi * (1 + 5 ** 0.5) * i
    return np.stack([np.cos(th) * np.sin(phi), np.cos(phi), np.sin(th) * np.sin(phi)], 1)

def hull(pts):
    D = dirs()
    idx = np.unique(np.argmax(pts @ D.T, axis=0))
    return pts[idx]

out = {}
for name in ['moon_rock1', 'moon_rock2', 'moon_rockfield']:
    v, t = load('assets/props/%s.glb' % name)
    parts = components(v, t) if name == 'moon_rockfield' else [v]
    hs = []
    for p in parts:
        if len(p) < 30: continue
        hs.append(hull(p))
    out[name] = hs
    print(name, len(hs), [len(h) for h in hs])
with open('scripts/rock_hulls.gd', 'w') as f:
    f.write('class_name NFRockHulls\n## Generated by tools/rock_hulls.py from the owner\'s rock models (which stay as he sent them):\n')
    f.write('## the convex hull of each rock, and of each boulder of the rock field, in the model\'s own space,\n')
    f.write('## as flat x, y, z lists (a const must be plain numbers).\n')
    f.write('const HULLS := {\n')
    for k, hs in out.items():
        f.write('\t"%s": [\n' % k)
        for h in hs:
            f.write('\t\t[%s],\n' % ', '.join('%.3f, %.3f, %.3f' % tuple(p) for p in h))
        f.write('\t],\n')
    f.write('}\n')
